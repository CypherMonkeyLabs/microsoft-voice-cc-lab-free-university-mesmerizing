/* Rewrite campus/sw.js precache.
   The critical shell (chat, icons, one lesson track, app) stays under 3.5 MB.
   The full list keeps the previous offline set and stays under 20 MB.
   Usage: node scripts/build_precache.mjs
*/
import { createHash } from "node:crypto";
import { readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const campus = join(repo, "campus");
const criticalBudget = 3_500_000;
const fullBudget = 20_000_000;
const base = JSON.parse(readFileSync(join(repo, "scripts/precache-base.json"), "utf8"));

const critical = [
  "./",
  "./index.html",
  "./offline.html",
  "./cert-match.html",
  "./app.css",
  "./chrome.css",
  "./app.js",
  "./guide.js",
  "./fx.js",
  "./effects.js",
  "./sources-deeper.js",
  "./bot/engine.js",
  "./bot/ui.js",
  "./bot/chat.css",
  "./bot/host.js",
  "./bot/voicebot-index.json",
  "./manifest.webmanifest",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
  "./icons/icon-maskable-512.png",
  "./favicon.svg",
  "./favicon.ico",
  "./data/manifest.json",
  "./data/tracks/t01.json",
];

const full = [...new Set([...base, ...critical])].sort((a, b) => a.localeCompare(b));

function bytes(rel) {
  const file = rel === "./" ? join(campus, "index.html") : join(campus, rel.slice(2));
  return statSync(file).size;
}

let criticalBytes = 0;
for (const rel of critical) criticalBytes += bytes(rel);
let fullBytes = 0;
const missing = [];
for (const rel of full) {
  try {
    fullBytes += bytes(rel);
  } catch (err) {
    missing.push(rel);
  }
}
console.log("critical", critical.length, "files", criticalBytes, "bytes");
console.log("full", full.length, "files", fullBytes, "bytes");
if (missing.length) {
  for (const rel of missing) console.error("MISSING", rel);
  process.exit(1);
}
if (criticalBytes > criticalBudget) {
  console.error("FAIL critical precache over 3.5 MB");
  process.exit(1);
}
if (fullBytes > fullBudget) {
  console.error("FAIL full precache over 20 MB");
  process.exit(1);
}

const hash = createHash("sha256").update(full.join("\n")).digest("hex").slice(0, 12);
const cache = `mvcc-lab-v5-${hash}`;
const body = `/* Offline cache for the Voice Lab. Generated by scripts/build_precache.mjs. */
"use strict";
const CACHE = ${JSON.stringify(cache)};
const PRECACHE = ${JSON.stringify(full, null, 2)};
self.addEventListener("install", function (event) {
  event.waitUntil(caches.open(CACHE).then(function (cache) { return cache.addAll(PRECACHE); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener("activate", function (event) {
  event.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (key) { return key !== CACHE; }).map(function (key) { return caches.delete(key); }));
  }).then(function () { return self.clients.claim(); }));
});
self.addEventListener("fetch", function (event) {
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || event.request.method !== "GET") return;
  event.respondWith(caches.match(event.request).then(function (cached) {
    const fetched = fetch(event.request).then(function (response) {
      if (response && response.ok) {
        const copy = response.clone();
        caches.open(CACHE).then(function (cache) { cache.put(event.request, copy); });
      }
      return response;
    }).catch(function () {
      if (cached) return cached;
      if (event.request.mode === "navigate") return caches.match("./offline.html");
      return caches.match("./offline.html");
    });
    return cached || fetched;
  }));
});
`;
writeFileSync(join(campus, "sw.js"), body);
console.log("wrote campus/sw.js", cache);
